// Bundle the current sanitizer into CommonJS for Vercel's function loader.
// The sanitizer's htmlparser2 dependency is ESM-only; Node's require(ESM)
// interoperability is unavailable in that loader. Keep upstream security fixes.
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const require=createRequire(import.meta.url);
const entry=require.resolve('sanitize-html');
const pkg=JSON.parse(readFileSync(path.join(path.dirname(entry),'package.json'),'utf8'));
const directory='server-handlers/auto-mail/vendor';
mkdirSync(directory,{recursive:true});
const result=await build({entryPoints:[entry],outfile:path.join(directory,'sanitize-html.cjs'),bundle:true,platform:'node',format:'cjs',target:'node20',minify:true,legalComments:'eof',metafile:true,banner:{js:`// Generated by npm run generate:mail-sanitizer from sanitize-html ${pkg.version}. Do not edit.`}});
const roots=new Map();
for(const file of Object.keys(result.metafile.inputs)){
  let current=path.dirname(path.resolve(file));
  while(current!==path.dirname(current)){
    const manifest=path.join(current,'package.json');
    if(existsSync(manifest)){
      const value=JSON.parse(readFileSync(manifest,'utf8'));
      if(value.name){roots.set(current,value);break;}
    }
    current=path.dirname(current);
  }
}
const notices=[];
for(const [root,value] of roots){
  const license=['LICENSE','LICENSE.md','LICENSE.txt','LICENSE-MIT','license','license.md','license.txt'].map(name=>path.join(root,name)).find(existsSync);
  notices.push(`${value.name} ${value.version}\n${license?readFileSync(license,'utf8'):`License: ${value.license||'See upstream package'}`}\n`);
}
writeFileSync(path.join(directory,'sanitize-html.LICENSE.txt'),notices.join('\n----------------------------------------\n\n'));
console.log(`Bundled sanitize-html ${pkg.version} and ${roots.size} dependency license notices.`);
